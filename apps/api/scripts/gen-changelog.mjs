// Embeds the repository CHANGELOG.md in the Worker bundle: a Worker has no file system, so
// modules/settings/updates.ts cannot read it at run time. Run after the changelog changes
// (the release script does); changelog.vtest.ts fails while the generated module is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../../../CHANGELOG.md', import.meta.url));
const target = fileURLToPath(
  new URL('../src/modules/settings/changelog.generated.ts', import.meta.url),
);
const markdown = readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
writeFileSync(
  target,
  `// Generated by scripts/gen-changelog.mjs from CHANGELOG.md. Do not edit.\nexport const CHANGELOG_MARKDOWN: string = ${JSON.stringify(markdown)};\n`,
);
